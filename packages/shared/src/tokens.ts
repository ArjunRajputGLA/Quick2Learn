/**
 * Generates the Tailwind CSS v4 token stylesheet (@theme and :root variables)
 * for apps/web/src/styles/tokens.css
 */
export function generateWebTokenCss(): string {
  const lines: string[] = [
    '/* ========================================================================= */',
    '/* AUTO-GENERATED by `pnpm tokens:build` from packages/shared/src/tokens.ts.   */',
    '/* DO NOT EDIT DIRECTLY. Change values in tokens.ts and run `pnpm tokens:build` */',
    '/* ========================================================================= */',
    '',
    '@theme {',
  ];

  // Colors
  for (const [key, val] of Object.entries(colors)) {
    lines.push(`  --color-${key}: ${val};`);
  }
  lines.push('');

  // Radii
  for (const [key, val] of Object.entries(radii)) {
    lines.push(`  --radius-${key}: ${val === 9999 ? '9999px' : `${val}px`};`);
  }
  lines.push('');

  // Shadows
  lines.push(`  --shadow-card: ${shadows.card};`);
  lines.push(`  --shadow-card-hover: ${shadows.cardHover};`);
  lines.push('');

  // Font family
  lines.push('  --font-sans: var(--font-inter), var(--font-devanagari), system-ui, -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif;');
  lines.push('');

  // Web type scale
  for (const [key, val] of Object.entries(webTypeScale)) {
    lines.push(`  --text-${key}: ${val.fontSize}px;`);
    lines.push(`  --text-${key}--line-height: ${val.lineHeight}px;`);
  }

  lines.push('}');
  lines.push('');

  // :root fallback variables for CSS custom property references
  lines.push(':root {');
  for (const [key, val] of Object.entries(colors)) {
    lines.push(`  --color-${key}: ${val};`);
  }
  lines.push('');
  for (const [key, val] of Object.entries(radii)) {
    lines.push(`  --radius-${key}: ${val === 9999 ? '9999px' : `${val}px`};`);
  }
  lines.push('');
  lines.push('  --content-max-width: 1200px;');
  lines.push('}');
  lines.push('');

  return lines.join('\n');
}
